#!/usr/bin/env python3
"""gen_dequant_ref_comp.py - build the reference-oracle shader source for the dequant fidelity test.

_dequant_ptq1_0.comp (repo root) is the OFFICIAL PrismML/llama.cpp vulkan-shaders body, kept
byte-for-byte as it came out of the fork. It starts with

    #version 450
    #include "dequant_head.glsl"

and ggml-vulkan resolves that include at *its* build time by prepending generated code. glslang.exe
refuses the directive unless the shader requests GL_GOOGLE_include_directive, which the official
source does not - so we do the concatenation here instead of editing the official body.

Output: runtime_vk/shaders/dequant_ptq1_0_ref.comp  (compiled by build_mingw.bat's shader loop)
    #version 450                <- exactly one, from the official file
    <dequant_head.glsl minus its own guard comments/ifndef lines>
    <official body minus its #version and #include lines>

Nothing in the arithmetic is touched: the body is copied verbatim, line for line.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "_dequant_ptq1_0.comp"          # the official body, kept as fetched from the fork
HEAD = ROOT / "runtime_vk" / "shaders" / "dequant_head.glsl"
OUT = ROOT / "runtime_vk" / "shaders" / "dequant_ptq1_0_ref.comp"

body = SRC.read_text(encoding="utf-8").splitlines()
if body[0].strip() != "#version 450":
    raise SystemExit(f"{SRC.name}: unexpected first line {body[0]!r} - re-read the official file")
kept_body = [ln for ln in body[1:] if not ln.lstrip().startswith("#include")]

head = HEAD.read_text(encoding="utf-8").splitlines()
# drop only the #ifndef/#define/#endif include guard lines; the #extension and struct stay
kept_head = [ln for ln in head
             if not ln.lstrip().startswith(("#ifndef", "#define BONSAI", "#endif"))]

out = ["// GENERATED by tools/gen_dequant_ref_comp.py - do not edit. Official body verbatim, head inlined.",
       "#version 450", ""] + kept_head + [""] + kept_body
OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {OUT}  ({len(out)} lines: {len(kept_head)} head + {len(kept_body)} official)")
